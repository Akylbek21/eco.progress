-- Явный признак "позиция контроля выполняется по всем точкам мониторинга".
--
-- До этого признака пустой monitoring_point_id неявно означал "все точки": ProtocolPekCreationService
-- размножал такую позицию по каждой точке направления. Беда в том, что "осознанно по всем точкам" и
-- "точку просто забыли указать" выглядели в базе одинаково, и второй случай молча давал декартово
-- произведение - в программе с позициями "северная"/"южная" и точками ТК-01/ТК-02 вместо двух
-- требований появлялось четыре.
--
-- Теперь это три разных состояния:
--   applies_to_all_points = TRUE            -> по всем точкам, намеренно;
--   monitoring_point_id IS NOT NULL         -> ровно по этой точке;
--   ни то, ни другое                        -> позиция не настроена, требование отдаётся со статусом
--                                              CONFIGURATION_REQUIRED и по точкам НЕ размножается.
--
-- Бэкфилл: строки без точки получают TRUE, то есть ровно то поведение, которое у них было до сих пор.
-- Иначе миграция задним числом объявила бы все существующие программы ненастроенными, и у заказчика
-- разом отвалились бы требования, которые сейчас работают. Разбирать, где "все точки" было осознанным,
-- а где ошибкой заполнения, по данным нельзя - это делается вручную в интерфейсе программы.
-- В частности, позициям "северная"/"южная" из обращения точки нужно проставить руками.

ALTER TABLE pek_program_control_items
    ADD COLUMN applies_to_all_points BOOLEAN NOT NULL DEFAULT FALSE;

UPDATE pek_program_control_items
SET applies_to_all_points = TRUE
WHERE monitoring_point_id IS NULL;
