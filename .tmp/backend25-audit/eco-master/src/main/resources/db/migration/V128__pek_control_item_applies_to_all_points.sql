-- Явный признак "позиция контроля выполняется по всем точкам мониторинга".
--
-- До этого признака пустой monitoring_point_id неявно означал "все точки": ProtocolPekCreationService
-- размножал такую позицию по каждой точке направления. "Осознанно по всем точкам" и "точку забыли
-- указать" выглядели в базе одинаково, и второй случай молча давал декартово произведение - в
-- программе с позициями "северная"/"южная" и точками ТК-01/ТК-02 вместо двух требований было четыре.
--
-- Теперь у позиции ровно одна из двух настроек:
--   monitoring_point_id IS NOT NULL   -> только эта точка;
--   applies_to_all_points = TRUE      -> каждая точка направления.
-- Ни то, ни другое - позиция не настроена: требование отдаётся одно, со статусом
-- CONFIGURATION_REQUIRED, по точкам не размножается, протокол по нему создать нельзя.
--
-- Данные эта миграция СОЗНАТЕЛЬНО не трогает. Для существующей позиции без точки нельзя по данным
-- определить, имелись в виду "все точки" или точку просто не заполнили, а любое автоматическое
-- решение меняет смысл программы. Даже позиция в направлении с единственной точкой неоднозначна:
-- при добавлении второй точки "эта точка" и "все точки" начнут вести себя по-разному. Поэтому такие
-- позиции после миграции становятся CONFIGURATION_REQUIRED и настраиваются вручную - см.
-- docs/pek-control-item-points-data-fix.sql (отчёт по ненастроенным позициям и шаблон исправления
-- по явным ID точек, без сопоставления по названию).

ALTER TABLE pek_program_control_items
    ADD COLUMN applies_to_all_points BOOLEAN NOT NULL DEFAULT FALSE;
