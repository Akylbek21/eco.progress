export const getRegionalServiceNote = (regionSlug: string, serviceKey: string): RegionalServiceNote => {
  const base = serviceDefaults[serviceKey];
  if (!base) {
    throw new Error(`Missing regional service content for service: ${serviceKey}`);
  }

  return {
    ...base,
    ...regionalServiceNotes[regionSlug]?.[serviceKey],
  };
};
