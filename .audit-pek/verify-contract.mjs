import fs from 'node:fs';
import assert from 'node:assert/strict';
const read = p => fs.readFileSync(p, 'utf8');
const backend = read('.audit-pek/eco-master/src/main/java/kz/eco/pek/PekReportService.java');
const actions = Object.fromEntries([...backend.matchAll(/actions\.put\("([^"]+)"/g)].map(m => [m[1], true]));
assert.equal(actions.matchSources, true);
assert.equal(actions.manageSources === true, false);
assert.match(read('src/features/pek/pages/PekReportWorkspacePage.tsx'), /availableActions\.manageSources === true/);
console.log('CONFIRMED: backend matchSources does not enable UI manageSources');
assert.equal(actions.generatePackage === true, false);
assert.match(read('src/features/pek/components/documents/PekReportPackageCard.tsx'), /report\.availableActions\.generatePackage === true/);
console.log('CONFIRMED: first package generation has no backend action flag');
const missingFields = ['protocols[1].pdf'];
assert.equal(false || missingFields.length > 0, true);
assert.match(read('src/features/pek/components/documents/PekReportPackageCard.tsx'), /disabled=\{busy \|\| missingFields.length > 0\}/);
console.log('CONFIRMED: persisted missingFields disables package regeneration');
const safe = s => s.replace(/[\\/:*?"<>|]/g, '_');
const files = new Map();
files.set(safe('A/1'), 'first PDF');
files.set(safe('A:1'), 'second PDF');
assert.equal(files.size, 1);
console.log('CONFIRMED: sanitized protocol filename collisions overwrite a ZIP entry');
