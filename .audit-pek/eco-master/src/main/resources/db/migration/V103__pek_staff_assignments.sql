-- kz.eco.pek module fix item 1: replaces pek_company_memberships in the access-control path with
-- a dedicated "our staff assigned to a client company" table that can never represent a client
-- company's own employees (pek_company_memberships.role_code directly reused the generic
-- UserRole enum, including CLIENT, with nothing stopping that assignment).
CREATE TABLE pek_staff_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    tier VARCHAR(16) NOT NULL DEFAULT 'VIEWER',
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    assigned_by BIGINT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_pek_staff_assignment UNIQUE (company_id, user_id)
);
CREATE INDEX idx_pek_staff_assignments_company ON pek_staff_assignments (company_id, status);
CREATE INDEX idx_pek_staff_assignments_user ON pek_staff_assignments (user_id, status);

-- One-time backfill: every pek_company_memberships row whose user is a real staff account (never
-- CLIENT) is carried across so existing operational access does not silently vanish on deploy.
-- Tier mapping mirrors the old inline EDIT_MEMBERSHIP_ROLES/REVIEW_MEMBERSHIP_ROLES sets that used
-- to live in PekAccessService.
INSERT INTO pek_staff_assignments (company_id, user_id, tier, status, assigned_by, created_at, updated_at, version)
SELECT
    m.company_id,
    m.user_id,
    CASE
        WHEN m.role_code IN ('ADMIN', 'DIRECTOR', 'HEAD') THEN 'REVIEWER'
        WHEN m.role_code = 'ECOLOGIST' THEN 'EDITOR'
        ELSE 'VIEWER'
    END,
    m.status,
    m.invited_by,
    m.created_at,
    m.updated_at,
    0
FROM pek_company_memberships m
JOIN users u ON u.id = m.user_id
WHERE u.role <> 'CLIENT';
